// Writes the letter, bigram and trigram counts of the Bombe's language model to
// src/backend/Enigma.Domain/Bombe/LanguageCounts.cs. German: data/corpus/effi-briest.txt, converted to Navy style
// (ä → AE, ö → OE, ü → UE, ß → SZ, CH → Q, digits spelled out, punctuation → X, no spaces). Navy: the plain texts of
// the bundled intercepts and of exercises sampled from the templates.
// Run from anywhere: dotnet run scripts/LanguageTable.cs
using System.Globalization;
using System.Text;
using Enigma.Domain.Bombe;

const string GermanSource = "Theodor Fontane, Effi Briest (1895), Project Gutenberg eBook #5323";
const int ExerciseSamples = 400;
const int Seed = 1;

var root = Path.GetFullPath(Path.Combine((string)AppContext.GetData("EntryPointFileDirectoryPath")!, ".."));

var book = File.ReadAllText(Path.Combine(root, "data", "corpus", "effi-briest.txt"));
var start = book.IndexOf("*** START OF", StringComparison.Ordinal);
var end = book.IndexOf("*** END OF", StringComparison.Ordinal);
var german = new Counts();
german.Add(NavyStyle(book[(book.IndexOf('\n', start) + 1)..end]));

var navy = new Counts();
foreach (var intercept in Intercepts.All)
{
    navy.Add(intercept.Source.Solution!.Plaintext);
}

var random = new Random(Seed);
for (var sample = 0; sample < ExerciseSamples; sample++)
{
    navy.Add(ExerciseGenerator.PlainText(random));
}

var code = new StringBuilder();
code.AppendLine("// <auto-generated>")
    .AppendLine("// Written by scripts/LanguageTable.cs. Do not edit.")
    .AppendLine("// </auto-generated>")
    .AppendLine()
    .AppendLine("namespace Enigma.Domain.Bombe;")
    .AppendLine()
    .AppendLine("/// <summary>")
    .AppendLine("/// Letter, bigram and trigram counts in Navy style: Navy from the bundled intercepts and "
        + $"{ExerciseSamples} exercise plain texts,")
    .AppendLine("/// German from the source named.")
    .AppendLine("/// </summary>")
    .AppendLine("internal static class LanguageCounts")
    .AppendLine("{")
    .AppendLine(CultureInfo.InvariantCulture, $"    public const string GermanSource = \"{GermanSource}\";");
Table("NavyLetters", navy.Letters);
Table("NavyBigrams", navy.Bigrams);
Table("NavyTrigrams", navy.Trigrams);
Table("GermanLetters", german.Letters);
Table("GermanBigrams", german.Bigrams);
Table("GermanTrigrams", german.Trigrams);
code.AppendLine("}");

var target = Path.Combine(root, "src", "backend", "Enigma.Domain", "Bombe", "LanguageCounts.cs");
File.WriteAllText(target, code.ToString().ReplaceLineEndings("\n"));
Console.WriteLine($"German: {german.Letters.Sum():N0} letters. Navy: {navy.Letters.Sum():N0} letters. Wrote {target}.");

void Table(string name, int[] counts)
{
    code.AppendLine().AppendLine(CultureInfo.InvariantCulture, $"    public static ReadOnlySpan<int> {name} =>").AppendLine("    [");
    foreach (var row in counts.Chunk(26))
    {
        code.AppendLine(CultureInfo.InvariantCulture, $"        {string.Join(", ", row)},");
    }

    code.AppendLine("    ];");
}

static string NavyStyle(string text)
{
    string[] digits = ["NUL", "EINS", "ZWO", "DREI", "VIER", "FUENF", "SEQS", "SIEBEN", "AQT", "NEUN"];
    var output = new StringBuilder();
    var word = new StringBuilder();
    var punctuation = false;

    foreach (var c in text)
    {
        var letters = char.ToUpperInvariant(c) switch
        {
            'Ä' => "AE",
            'Ö' => "OE",
            'Ü' => "UE",
            'ß' => "SZ",
            >= '0' and <= '9' => digits[c - '0'],
            var upper when char.IsLetter(upper) => Plain(upper),
            _ => null,
        };

        if (letters is not null)
        {
            if (punctuation && output.Length > 0)
            {
                output.Append('X');
            }

            punctuation = false;
            word.Append(letters);
        }
        else
        {
            output.Append(word.Replace("CH", "Q"));
            word.Clear();
            punctuation |= !char.IsWhiteSpace(c);
        }
    }

    return output.Append(word.Replace("CH", "Q")).ToString();
}

// A letter without its accent, or nothing when it is not a Latin letter.
static string Plain(char letter)
{
    var bare = letter.ToString().Normalize(NormalizationForm.FormD)[0];
    return bare is >= 'A' and <= 'Z' ? bare.ToString() : string.Empty;
}

internal sealed class Counts
{
    public int[] Letters { get; } = new int[26];

    public int[] Bigrams { get; } = new int[26 * 26];

    public int[] Trigrams { get; } = new int[26 * 26 * 26];

    public void Add(string text)
    {
        for (var index = 0; index < text.Length; index++)
        {
            var c = text[index] - 'A';
            Letters[c]++;
            if (index >= 1)
            {
                var b = text[index - 1] - 'A';
                Bigrams[(b * 26) + c]++;
                if (index >= 2)
                {
                    Trigrams[(((text[index - 2] - 'A') * 26) + b) * 26 + c]++;
                }
            }
        }
    }
}
